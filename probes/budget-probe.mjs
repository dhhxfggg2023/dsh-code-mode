// ---------------------------------------------------------------- stub cordis context
function makeCtx() {
  const handlers = new Map();
  const order = [];
  return {
    handlers,
    order,
    on(event, handler) {
      order.push(event);
      if (!handlers.has(event)) handlers.set(event, []);
      handlers.get(event).push(handler);
      return () => {};
    },
  };
}
const handlersOf = (ctx, event) => ctx.handlers.get(event) ?? [];
/** Cordis waterfall: next() runs the next listener, else the fallback decision. */
async function waterfall(hs, args, fallback) {
  let i = 0;
  const next = () =>
    i >= hs.length
      ? Promise.resolve(typeof fallback === 'function' ? fallback() : fallback)
      : Promise.resolve(hs[i++](...args, next));
  return next();
}
let seq = 0;
const execFor = (name, args, agent = { session: { id: 'sess-budget', header: { cwd: PROBE } } }) => ({
  token: 't',
  callId: `c${++seq}`,
  rootCallId: `c${seq}`,
  name,
  signal: undefined,
  agent,
  arguments: args,
});
/** Drives tools/pre-execute; counts whether the chain reached the downstream fallback. */
async function preExecuteDrive(ctx, exec, fallback = { kind: 'allow' }) {
  let nextCalls = 0;
  let decision;
  let error;
  try {
    decision = await waterfall(handlersOf(ctx, 'tools/pre-execute'), [exec], () => {
      nextCalls += 1;
      return fallback;
    });
  } catch (e) {
    error = errInfo(e);
  }
  return { decision, nextCalls, error };
}
/** Drives tools/post-execute with a caller-supplied downstream decision. */
async function postExecuteDrive(ctx, exec, result, downstream) {
  let nextCalls = 0;
  let decision;
  let error;
  try {
    decision = await waterfall(handlersOf(ctx, 'tools/post-execute'), [exec, result], () => {
      nextCalls += 1;
      return downstream;
    });
  } catch (e) {
    error = errInfo(e);
  }
  return { decision, nextCalls, error };
}

