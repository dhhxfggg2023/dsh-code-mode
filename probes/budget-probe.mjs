  const ctxZeroTrim = makeCtx();
  await mod.apply(ctxZeroTrim, { ...prodCfg, maxResultChars: 0 });
  const down3f = { kind: 'accept', content: [text(single)] };
  const d3f = await postExecuteDrive(ctxZeroTrim, execFor('read', { file_path: FILE_SMALL }, agent), { isError: false, content: [text(single)] }, down3f);
  check('3f.zero-disables-trim', 3, '{ maxResultChars: 0 } disables trimming', d3f.decision === down3f && d3f.error === undefined, { identical: d3f.decision === down3f, error: d3f.error ?? null });

  const errDown = { kind: 'accept', content: [text(single)] };
  const d3g = await postExecuteDrive(ctx3, execFor('read', { file_path: FILE_SMALL }, agent), { isError: true, content: [text(single)], error: { message: 'boom' } }, errDown);
